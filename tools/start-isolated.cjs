'use strict';
const {spawn}=require('node:child_process'),fs=require('node:fs'),path=require('node:path');
const repo=path.resolve(__dirname,'..'),profile=path.join(repo,'build/dev-profile');
require('./verify-release.cjs');
if(!fs.existsSync(path.join(repo,'build/assets/bundle/tia/base.gla')))throw Error('Run npm run import-release first.');
const env={...process.env};delete env.ELECTRON_RUN_AS_NODE;delete env.GLA_OPENAI_KEY;
console.log('Starting with separate development settings at '+profile+'. Enter your own voice key in Settings.');
const child=spawn(require('electron'),[repo,'--user-data-dir='+profile],{stdio:'inherit',env});
child.on('error',error=>{console.error(error.message);process.exitCode=1;});
child.on('exit',(code,signal)=>{process.exitCode=code??(signal?1:0);});
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,()=>child.kill(signal));
